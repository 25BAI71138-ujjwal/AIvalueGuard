import asyncio
import time
import json
import random
from typing import Optional, Tuple
from backend.app.services.provider_adapters.base import BaseProviderAdapter

class DemoProviderAdapter(BaseProviderAdapter):
    """
    High-fidelity deterministic demo provider.
    Provides realistic responses, token counts, and latency measurements without requiring paid API keys.
    Clearly flagged in metadata as DEMO DATA.
    """

    async def generate(
        self,
        model_id: str,
        prompt: str,
        system_instruction: Optional[str] = None,
        context: Optional[str] = None,
        temperature: float = 0.7,
        max_tokens: Optional[int] = 1024,
        json_mode: bool = False
    ) -> Tuple[str, int, int, float, Optional[float]]:
        start_time = time.perf_counter()

        # Simulate model-specific latency characteristics
        if "mini" in model_id or "flash" in model_id or "groq" in model_id or "haiku" in model_id:
            simulated_latency_sec = random.uniform(0.12, 0.28)
            ttft_ms = round(random.uniform(45.0, 95.0), 1)
        else:
            # Heavyweight models like gpt-4o, claude-3-5-sonnet
            simulated_latency_sec = random.uniform(0.40, 0.75)
            ttft_ms = round(random.uniform(140.0, 260.0), 1)

        await asyncio.sleep(simulated_latency_sec)

        prompt_lower = prompt.lower()
        full_input = f"{system_instruction or ''} {context or ''} {prompt}"
        prompt_tokens = max(12, int(len(full_input) / 3.8))

        # Dynamic demo response generation
        if json_mode or "json" in prompt_lower or "extract" in prompt_lower or "classify" in prompt_lower:
            response_dict = {
                "status": "success",
                "classification": "high_priority_billing_inquiry" if "refund" in prompt_lower or "bill" in prompt_lower else "technical_support",
                "confidence": 0.96,
                "summary": "Customer requested assistance with API billing and quota tier adjustments.",
                "action_items": [
                    "Verify current organization usage in billing portal",
                    "Check rate limits against provisioned tier",
                    "Route to specialist team if invoice dispute persists"
                ],
                "model_processed": model_id,
                "latency_tier": "fast_path" if "mini" in model_id or "flash" in model_id else "thorough"
            }
            completion_text = json.dumps(response_dict, indent=2)
        elif "summarize" in prompt_lower or "summary" in prompt_lower:
            completion_text = (
                f"**Executive Summary (Generated by {model_id}):**\n\n"
                "The provided content outlines core technical and cost constraints for scaling LLM workloads. "
                "Key takeaways include:\n"
                "1. **Cost Optimization**: Routing standard classification and extraction tasks to distilled models lowers inference spend by 70–90%.\n"
                "2. **Safe Caching**: Exact fingerprint caching eliminates redundant provider calls for repeated customer queries with 0% quality loss.\n"
                "3. **Quality Verification**: Automated structural validation ensures downstream services receive schema-compliant payloads without manual intervention."
            )
        elif "code" in prompt_lower or "function" in prompt_lower or "python" in prompt_lower or "typescript" in prompt_lower:
            completion_text = (
                f"// Generated solution via {model_id}\n"
                "export async function executeOptimizedInference(prompt: string, budgetMs = 800) {\n"
                "  const response = await fetch('/api/gateway/chat', {\n"
                "    method: 'POST',\n"
                "    headers: { 'Content-Type': 'application/json' },\n"
                "    body: JSON.stringify({\n"
                "      prompt,\n"
                "      latency_budget_ms: budgetMs,\n"
                "      optimize: true,\n"
                "      allow_cache: true\n"
                "    })\n"
                "  });\n"
                "  if (!response.ok) throw new Error(`Gateway returned ${response.status}`);\n"
                "  return await response.json();\n"
                "}\n"
            )
        else:
            completion_text = (
                f"Response processed by AIValueGuard Gateway utilizing **{model_id}**.\n\n"
                f"Your query: \"{prompt[:120]}{'...' if len(prompt) > 120 else ''}\"\n\n"
                "The gateway routed this request through the multi-criteria optimization pipeline, "
                "evaluating cost, context token budget, latency budgets, and output validation rules. "
                "All constraints were satisfied while maintaining high-fidelity response quality."
            )

        completion_tokens = max(24, int(len(completion_text) / 3.8))
        elapsed_ms = round((time.perf_counter() - start_time) * 1000.0, 1)

        return completion_text, prompt_tokens, completion_tokens, elapsed_ms, ttft_ms
